#!/usr/bin/env node
/**
 * Publishes @mixiuh/pixel-ui (packages/mixiuh-pixel-ui) to /public/pixel-ui:
 *   - mixiuh-pixel-ui.css      standalone CDN stylesheet (fonts included)
 *   - mixiuh-pixel-ui-kit.zip  downloadable kit (README, LICENSE, src, styles, cdn)
 *
 * Output is deterministic (fixed timestamps, sorted entries), so re-running it
 * without source changes leaves git clean. Runs automatically before `next build`.
 */
import fs from "node:fs";
import path from "node:path";
import zlib from "node:zlib";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const PKG_DIR = path.join(ROOT, "packages", "mixiuh-pixel-ui");
const OUT_DIR = path.join(ROOT, "public", "pixel-ui");

const pkg = JSON.parse(fs.readFileSync(path.join(PKG_DIR, "package.json"), "utf8"));
const versionSrc = fs.readFileSync(path.join(PKG_DIR, "src", "version.ts"), "utf8");
const versionMatch = versionSrc.match(/PIXEL_UI_VERSION\s*=\s*"([^"]+)"/);
if (!versionMatch || versionMatch[1] !== pkg.version) {
  console.error(
    `[pixel-ui:kit] Version mismatch: package.json=${pkg.version} src/version.ts=${versionMatch?.[1]}`
  );
  process.exit(1);
}

// ---------------------------------------------------------------------------
// 1. Standalone CDN stylesheet
// ---------------------------------------------------------------------------
const FONTS_URL =
  "https://fonts.googleapis.com/css2?family=Inter:wght@400;600;700&family=Pixelify+Sans:wght@400;500;600;700&family=Poppins:wght@600;700;800;900&family=Silkscreen:wght@400;700&family=Space+Mono:wght@400;700&display=swap";

const css = fs.readFileSync(path.join(PKG_DIR, "styles", "pixel-ui.css"), "utf8");
const cdnCss = `/* @mixiuh/pixel-ui v${pkg.version} — CDN build (generated by scripts/build-pixel-ui-kit.mjs, do not edit) */
@import url("${FONTS_URL}");

${css}`;

fs.mkdirSync(OUT_DIR, { recursive: true });
writeIfChanged(path.join(OUT_DIR, "mixiuh-pixel-ui.css"), cdnCss);

// ---------------------------------------------------------------------------
// 2. Deterministic ZIP kit
// ---------------------------------------------------------------------------
const entries = [];
const addFile = (zipPath, absPath) =>
  entries.push({ name: zipPath, data: fs.readFileSync(absPath) });

addFile("mixiuh-pixel-ui/README.md", path.join(PKG_DIR, "README.md"));
addFile("mixiuh-pixel-ui/LICENSE", path.join(PKG_DIR, "LICENSE"));
addFile("mixiuh-pixel-ui/package.json", path.join(PKG_DIR, "package.json"));
addFile("mixiuh-pixel-ui/styles/pixel-ui.css", path.join(PKG_DIR, "styles", "pixel-ui.css"));
for (const file of fs.readdirSync(path.join(PKG_DIR, "src")).sort()) {
  addFile(`mixiuh-pixel-ui/src/${file}`, path.join(PKG_DIR, "src", file));
}
entries.push({ name: "mixiuh-pixel-ui/cdn/mixiuh-pixel-ui.css", data: Buffer.from(cdnCss) });
entries.sort((a, b) => a.name.localeCompare(b.name));

writeIfChanged(path.join(OUT_DIR, "mixiuh-pixel-ui-kit.zip"), buildZip(entries));

console.log(
  `[pixel-ui:kit] v${pkg.version}: ${entries.length} files -> public/pixel-ui/{mixiuh-pixel-ui.css,mixiuh-pixel-ui-kit.zip}`
);

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------
function writeIfChanged(file, content) {
  const next = Buffer.isBuffer(content) ? content : Buffer.from(content);
  if (fs.existsSync(file) && fs.readFileSync(file).equals(next)) return;
  fs.writeFileSync(file, next);
}

function crc32(buf) {
  if (zlib.crc32) return zlib.crc32(buf) >>> 0;
  let c = 0xffffffff;
  for (let i = 0; i < buf.length; i++) {
    c ^= buf[i];
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  }
  return (c ^ 0xffffffff) >>> 0;
}

/** Minimal ZIP (deflate) writer with a fixed DOS timestamp: 2026-10-30 00:00. */
function buildZip(files) {
  const DOS_TIME = 0;
  const DOS_DATE = ((2026 - 1980) << 9) | (10 << 5) | 30;
  const locals = [];
  const centrals = [];
  let offset = 0;

  for (const { name, data } of files) {
    const nameBuf = Buffer.from(name, "utf8");
    const compressed = zlib.deflateRawSync(data, { level: 9 });
    const crc = crc32(data);

    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4); // version needed
    local.writeUInt16LE(0x0800, 6); // UTF-8 names
    local.writeUInt16LE(8, 8); // deflate
    local.writeUInt16LE(DOS_TIME, 10);
    local.writeUInt16LE(DOS_DATE, 12);
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(compressed.length, 18);
    local.writeUInt32LE(data.length, 22);
    local.writeUInt16LE(nameBuf.length, 26);
    local.writeUInt16LE(0, 28);
    locals.push(local, nameBuf, compressed);

    const central = Buffer.alloc(46);
    central.writeUInt32LE(0x02014b50, 0);
    central.writeUInt16LE(0x0314, 4); // made by: UNIX, v2.0
    central.writeUInt16LE(20, 6);
    central.writeUInt16LE(0x0800, 8);
    central.writeUInt16LE(8, 10);
    central.writeUInt16LE(DOS_TIME, 12);
    central.writeUInt16LE(DOS_DATE, 14);
    central.writeUInt32LE(crc, 16);
    central.writeUInt32LE(compressed.length, 20);
    central.writeUInt32LE(data.length, 24);
    central.writeUInt16LE(nameBuf.length, 28);
    central.writeUInt16LE(0, 30); // extra
    central.writeUInt16LE(0, 32); // comment
    central.writeUInt16LE(0, 34); // disk
    central.writeUInt16LE(0, 36); // internal attrs
    central.writeUInt32LE((0o100644 << 16) >>> 0, 38); // -rw-r--r--
    central.writeUInt32LE(offset, 42);
    centrals.push(central, nameBuf);

    offset += local.length + nameBuf.length + compressed.length;
  }

  const centralSize = centrals.reduce((n, b) => n + b.length, 0);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(files.length, 8);
  end.writeUInt16LE(files.length, 10);
  end.writeUInt32LE(centralSize, 12);
  end.writeUInt32LE(offset, 16);

  return Buffer.concat([...locals, ...centrals, end]);
}
